import {readFileSync, existsSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const required=['index.html','cloud.js','cloud.css','supabase-config.js','manifest.webmanifest','sw.js','icon.svg'];
for(const f of required)assert.ok(existsSync(f),`Falta ${f}`);
const index=readFileSync('index.html','utf8');
for(const f of ['cloud.js','cloud.css','supabase-config.js','manifest.webmanifest','sw.js']) assert.ok(index.includes(f)||f==='sw.js',`Recurso ${f} no está enlazado`);
const scripts=[...index.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
for(const [i,m] of scripts.entries()) if(m[1].trim())new vm.Script(m[1],{filename:`inline-script-${i}.js`});
for(const f of ['cloud.js','supabase-config.js','sw.js'])new vm.Script(readFileSync(f,'utf8'),{filename:f});
const manifest=JSON.parse(readFileSync('manifest.webmanifest','utf8'));
assert.equal(manifest.display,'standalone');
assert.ok(manifest.icons?.every(icon=>existsSync(icon.src)));
assert.ok(index.includes('return renderHomeTimePicker()+renderDailyHome()+renderDialogueSpotlight()+renderHomeMomentum()'),'El selector de tiempo debe abrir la portada');
assert.ok(index.includes('¿Cuánto te queda hoy?'),'Falta selector de tiempo');
assert.ok(index.includes('OBJETIVO DIARIO · ~2–3 MIN'),'Falta meta diaria explícita');
assert.ok(index.includes('dailyCompletedCount(record)'),'El contador debe leer progreso del día');
assert.ok(!index.includes('body::before{'),'No debe existir capa fixed decorativa delante del contenido táctil en iOS');
assert.ok(index.includes('touch-action:manipulation'),'Falta optimización de interacción táctil');
assert.ok(index.includes('padding-top:max(env(safe-area-inset-top,0px),54px)'),'iOS instalado: debe respetar zona segura sobre la Dynamic Island');
assert.ok(index.includes('.topbar-metrics>span{display:none}'),'iPhone: deja espacio para botón de cuenta en el encabezado');
const cloud=readFileSync('cloud.js','utf8');
assert.ok(cloud.includes('cloud-home-entry'),'Falta acceso a la cuenta desde la portada móvil');
assert.ok(readFileSync('cloud.css','utf8').includes('padding-top:max(env(safe-area-inset-top,0px),58px)'),'El diálogo debe respetar la zona segura iOS');
assert.ok(cloud.includes("signInWithOAuth({provider:'google'"),'Falta Google OAuth');
assert.ok(cloud.includes('data-action="cloud-google"'),'Falta el botón Google');
assert.ok(readFileSync('cloud.css','utf8').includes('.cloud-google-button'),'Falta el estilo Google');
const config=readFileSync('supabase-config.js','utf8');
assert.ok(config.includes('sb_publishable_'),'Falta clave pública de Supabase');
assert.ok(!config.includes('sb_secret_')&&!config.includes('service_role'),'No subas credenciales privadas');
console.log('✓ СЛОВО: comprobación estática terminada');
